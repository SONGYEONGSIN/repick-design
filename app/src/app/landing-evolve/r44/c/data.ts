// Deterministic sell-through model + catalog data for the Sell-Through Simulator.
// No Math.random / Date.now / new Date anywhere — `dailyRate(price)` is a fixed closed-form
// function of price only, so the same price always produces the exact same depletion curve,
// on the server and on the client, on every render.

export const INVENTORY_UNITS = 120; // units in this lot when the simulation starts
export const HORIZON_DAYS = 14; // fixed simulation window

export const MIN_PRICE = 40;
export const MAX_PRICE = 220;
export const PRICE_STEP = 5;
export const DEFAULT_PRICE = 95;

// Iso-elastic demand curve: rate(price) = BASE_RATE * (REF_PRICE / price) ^ ELASTICITY.
// List above REF_PRICE and the daily sell rate falls below BASE_RATE (slower depletion);
// list below it and the rate climbs above BASE_RATE (faster depletion). ELASTICITY controls
// how sharply rate reacts to price — this is the one formula the whole page threads through.
export const REF_PRICE = 120;
export const BASE_RATE = 9; // units/day sold when listed exactly at REF_PRICE
export const ELASTICITY = 1.5;

/** Units sold per day at a given list price. Pure function of price — no state, no time. */
export function dailyRate(price: number): number {
  return BASE_RATE * Math.pow(REF_PRICE / price, ELASTICITY);
}

export type DepletionPoint = { day: number; remaining: number };

/** Remaining inventory at the end of each simulated day, day 0 through HORIZON_DAYS. */
export function computeDepletionCurve(price: number): DepletionPoint[] {
  const rate = dailyRate(price);
  const points: DepletionPoint[] = [{ day: 0, remaining: INVENTORY_UNITS }];
  let remaining = INVENTORY_UNITS;
  for (let day = 1; day <= HORIZON_DAYS; day++) {
    remaining = Math.max(0, remaining - rate);
    points.push({ day, remaining: Math.round(remaining * 10) / 10 });
  }
  return points;
}

/** The day the lot hits zero remaining, or null if it never clears inside the horizon. */
export function sellOutDay(price: number): number | null {
  const rate = dailyRate(price);
  const exactDay = INVENTORY_UNITS / rate;
  return exactDay <= HORIZON_DAYS ? Math.max(1, Math.ceil(exactDay)) : null;
}

export function unitsRemainingAt(curve: DepletionPoint[]): number {
  return curve[curve.length - 1].remaining;
}

export function pctSoldAt(curve: DepletionPoint[]): number {
  const remaining = unitsRemainingAt(curve);
  return Math.round(((INVENTORY_UNITS - remaining) / INVENTORY_UNITS) * 100);
}

export function discountPct(before: number, after: number): number {
  return Math.round((1 - after / before) * 100);
}

export function formatUsd(n: number): string {
  return `$${n.toLocaleString("en-US")}`;
}

/** The single headline derived from the curve — the figure threaded to the closing CTA. */
export function headlineFor(price: number, curve: DepletionPoint[]) {
  const day = sellOutDay(price);
  if (day !== null) {
    return {
      clears: true as const,
      day,
      pct: 100,
      short: `${day}d`,
      sentence: `Clears 100% of inventory in ${day} day${day === 1 ? "" : "s"}.`,
      cta: `it clears in ${day} day${day === 1 ? "" : "s"}`,
    };
  }
  const pct = pctSoldAt(curve);
  const remaining = Math.round(unitsRemainingAt(curve));
  return {
    clears: false as const,
    day: HORIZON_DAYS,
    pct,
    short: `${pct}%`,
    sentence: `${pct}% sold through by day ${HORIZON_DAYS} — about ${remaining} unit${remaining === 1 ? "" : "s"} still unsold at this price.`,
    cta: `only ${pct}% of it clears by day ${HORIZON_DAYS}`,
  };
}

